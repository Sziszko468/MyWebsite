// Makes smaller WebP copies (480 and 800 px wide) of the project screenshots in public/projects, and writes the list the
// website reads (src/content/imageVariants.ts), so a phone downloads the size it can show instead of the 1440 px original.
//
// No image library is a dependency of this project, so the resizing is done by the system Chrome (Playwright, the same
// way tools/audit works): the picture is decoded, drawn to a canvas with high-quality smoothing and encoded as WebP.
//
//   AUDIT_PLAYWRIGHT=/path/to/node_modules/playwright node tools/images/make-variants.cjs [--quality=0.8]
//
// The original files are never changed. Running it again replaces the copies (a file named `-480.webp` or `-800.webp` is
// treated as a copy and skipped as a source). Commit the copies and the generated list.
const fs = require('fs')
const path = require('path')
const { chromium } = require(process.env.AUDIT_PLAYWRIGHT || 'playwright')

const ROOT = path.resolve(__dirname, '../..')
const DIR = path.join(ROOT, 'public/projects')
const OUT_TS = path.join(ROOT, 'src/content/imageVariants.ts')
const WIDTHS = [480, 800]
const quality = Number((process.argv.find((a) => a.startsWith('--quality=')) || '--quality=0.8').split('=')[1])

function* walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) yield* walk(full)
    else if (/\.webp$/.test(entry.name) && !/-(480|800)\.webp$/.test(entry.name)) yield full
  }
}

;(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  const page = await browser.newPage()
  const manifest = {}
  let before = 0
  let after = 0
  const rows = []
  for (const file of [...walk(DIR)].sort()) {
    const publicPath = '/' + path.relative(path.join(ROOT, 'public'), file).split(path.sep).join('/')
    const original = fs.readFileSync(file)
    const made = await page.evaluate(
      async ({ b64, widths, q }) => {
        const bytes = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0))
        const bitmap = await createImageBitmap(new Blob([bytes], { type: 'image/webp' }))
        const result = { width: bitmap.width, height: bitmap.height, copies: [] }
        for (const w of widths) {
          // A copy is only worth making when it is clearly smaller than the original.
          if (bitmap.width < w * 1.25) continue
          const h = Math.round((bitmap.height * w) / bitmap.width)
          const canvas = new OffscreenCanvas(w, h)
          const ctx = canvas.getContext('2d')
          ctx.imageSmoothingEnabled = true
          ctx.imageSmoothingQuality = 'high'
          ctx.drawImage(bitmap, 0, 0, w, h)
          const blob = await canvas.convertToBlob({ type: 'image/webp', quality: q })
          const buffer = new Uint8Array(await blob.arrayBuffer())
          let binary = ''
          for (let i = 0; i < buffer.length; i += 0x8000) binary += String.fromCharCode(...buffer.subarray(i, i + 0x8000))
          result.copies.push({ w, b64: btoa(binary) })
        }
        return result
      },
      { b64: original.toString('base64'), widths: WIDTHS, q: quality },
    )
    const entries = []
    for (const copy of made.copies) {
      const out = file.replace(/\.webp$/, `-${copy.w}.webp`)
      const buffer = Buffer.from(copy.b64, 'base64')
      // Only keep a copy that really saves bytes.
      if (buffer.length >= original.length * 0.85) continue
      fs.writeFileSync(out, buffer)
      entries.push([copy.w, publicPath.replace(/\.webp$/, `-${copy.w}.webp`)])
      rows.push(`${publicPath}  ${made.width}px ${(original.length / 1024).toFixed(0)} kB -> ${copy.w}px ${(buffer.length / 1024).toFixed(0)} kB`)
    }
    if (entries.length) manifest[publicPath] = { width: made.width, copies: entries }
    before += original.length
  }
  await browser.close()

  const body = Object.entries(manifest)
    .map(([src, { width, copies }]) => `  '${src}': { width: ${width}, copies: [${copies.map(([w, p]) => `[${w}, '${p}']`).join(', ')}] },`)
    .join('\n')
  fs.writeFileSync(
    OUT_TS,
    `// Generated by tools/images/make-variants.cjs. Do not edit: run the script again after adding a picture to public/projects.
export interface ImageVariants {
  /** The original's width in pixels. */
  width: number
  /** Smaller copies: [width in pixels, path]. */
  copies: readonly (readonly [number, string])[]
}

export const imageVariants: Readonly<Record<string, ImageVariants>> = {
${body}
}
`,
  )
  for (const row of rows) console.log(row)
  console.log(`${Object.keys(manifest).length} pictures have smaller copies; list written to ${path.relative(ROOT, OUT_TS)}`)
  void after
})()
